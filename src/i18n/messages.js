export function translate(language, key, params = {}) {
  const template = messages[language]?.[key] ?? messages.zh[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    Object.hasOwn(params, name) ? String(params[name]) : match,
  );
}
